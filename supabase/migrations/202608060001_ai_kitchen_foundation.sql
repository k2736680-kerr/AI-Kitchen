create or replace function public.ai_kitchen_reserve_generation(
  p_request_id text,
  p_idempotency_key text,
  p_request_hash text,
  p_schema_version text,
  p_client_version text,
  p_locale text,
  p_request_payload jsonb
) returns jsonb
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_owner uuid := auth.uid();
  v_row public.ai_kitchen_generation_requests%rowtype;
begin
  if v_owner is null then raise exception 'authentication required'; end if;

  select * into v_row
  from public.ai_kitchen_generation_requests
  where owner_id = v_owner and idempotency_key = p_idempotency_key
  for update;
  if not found then
    select * into v_row
    from public.ai_kitchen_generation_requests
    where owner_id = v_owner and request_id = p_request_id
    for update;
  end if;

  if found then
    if v_row.request_hash <> p_request_hash then return jsonb_build_object('kind', 'conflict'); end if;
    if v_row.status = 'processing' then return jsonb_build_object('kind', 'in_progress'); end if;
    if v_row.response_payload is not null then return jsonb_build_object('kind', 'replay', 'response', v_row.response_payload); end if;
    return jsonb_build_object('kind', 'conflict');
  end if;

  begin
    insert into public.ai_kitchen_generation_requests (
      owner_id, request_id, idempotency_key, request_hash, schema_version,
      client_version, locale, request_payload, status
    ) values (
      v_owner, p_request_id, p_idempotency_key, p_request_hash, p_schema_version,
      p_client_version, p_locale, p_request_payload, 'processing'
    );
  exception when unique_violation then
    select * into v_row
    from public.ai_kitchen_generation_requests
    where owner_id = v_owner and (idempotency_key = p_idempotency_key or request_id = p_request_id)
    order by case when idempotency_key = p_idempotency_key then 0 else 1 end
    limit 1
    for update;
    if v_row.request_hash <> p_request_hash then return jsonb_build_object('kind', 'conflict'); end if;
    if v_row.status = 'processing' then return jsonb_build_object('kind', 'in_progress'); end if;
    if v_row.response_payload is not null then return jsonb_build_object('kind', 'replay', 'response', v_row.response_payload); end if;
    return jsonb_build_object('kind', 'conflict');
  end;
  return jsonb_build_object('kind', 'new');
end;
$$;

create or replace function public.ai_kitchen_complete_generation(
  p_idempotency_key text,
  p_request_hash text,
  p_status text,
  p_response jsonb,
  p_duration_ms integer
) returns void
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  if auth.uid() is null then raise exception 'authentication required'; end if;
  if p_status not in ('succeeded', 'no_match') then raise exception 'invalid completion status'; end if;
  update public.ai_kitchen_generation_requests
  set status = p_status, response_payload = p_response, duration_ms = p_duration_ms,
      completed_at = clock_timestamp(), updated_at = clock_timestamp(), error_code = null
  where owner_id = auth.uid() and idempotency_key = p_idempotency_key and request_hash = p_request_hash;
  if not found then raise exception 'generation reservation not found'; end if;
end;
$$;

create or replace function public.ai_kitchen_fail_generation(
  p_idempotency_key text,
  p_request_hash text,
  p_status text,
  p_error_code text,
  p_duration_ms integer
) returns void
