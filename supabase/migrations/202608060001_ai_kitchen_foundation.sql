create table public.ai_kitchen_generation_requests (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users (id) on delete cascade,
  request_id text not null check (char_length(request_id) between 8 and 128),
  idempotency_key text not null check (char_length(idempotency_key) between 16 and 128),
  request_hash text not null check (request_hash ~ '^[0-9a-f]{64}$'),
  schema_version text not null,
  client_version text not null,
  locale text not null default 'zh-CN' check (locale in ('zh-CN', 'en-US')),
  request_payload jsonb not null,
  status text not null check (status in ('processing', 'succeeded', 'no_match', 'failed', 'timeout', 'service_unavailable', 'rate_limited')),
  response_payload jsonb,
  error_code text,
  provider_request_id text,
  duration_ms integer check (duration_ms is null or duration_ms >= 0),
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  completed_at timestamptz,
  unique (owner_id, request_id),
  unique (owner_id, idempotency_key)
);

create index ai_kitchen_generation_owner_created_idx on public.ai_kitchen_generation_requests (owner_id, created_at desc);
create index ai_kitchen_generation_status_updated_idx on public.ai_kitchen_generation_requests (status, updated_at desc);

create table public.ai_kitchen_recipes (
  recipe_id uuid primary key,
  owner_id uuid not null references auth.users (id) on delete cascade,
  schema_version text not null,
  source text not null check (source in ('local', 'deterministic', 'provider')),
  provider text,
  model text,
  title text not null,
  locale text not null default 'zh-CN' check (locale in ('zh-CN', 'en-US')),
  cooking_method text check (cooking_method is null or cooking_method in ('stir-fry', 'stew', 'steam', 'soup', 'cold', 'roast')),
  cuisine text check (cuisine is null or cuisine in ('sichuan', 'cantonese', 'hunan', 'jiangsu', 'zhejiang', 'northeastern', 'shandong', 'western', 'japanese', 'korean', 'other')),
  flavor text check (flavor is null or flavor in ('light', 'spicy', 'savory', 'sweet', 'sour', 'sweet-sour', 'salty')),
  recipe_payload jsonb not null,
  created_at timestamptz not null default clock_timestamp(),
  updated_at timestamptz not null default clock_timestamp(),
  unique (owner_id, recipe_id)
);

create index ai_kitchen_recipe_owner_locale_idx on public.ai_kitchen_recipes (owner_id, locale, created_at desc);

create table public.ai_kitchen_recipe_history (
  id bigint generated by default as identity primary key,
  owner_id uuid not null references auth.users (id) on delete cascade,
  recipe_id uuid not null,
  source text not null check (source in ('local', 'remote')),
  first_visited_at timestamptz not null default clock_timestamp(),
  last_visited_at timestamptz not null default clock_timestamp(),
  visit_count integer not null default 1 check (visit_count > 0),
  unique (owner_id, recipe_id),
  foreign key (owner_id, recipe_id) references public.ai_kitchen_recipes (owner_id, recipe_id) on delete cascade
);

create index ai_kitchen_history_owner_last_visited_idx on public.ai_kitchen_recipe_history (owner_id, last_visited_at desc, recipe_id desc);

create table public.ai_kitchen_rate_limits (
  owner_id uuid primary key references auth.users (id) on delete cascade,
  window_started_at timestamptz not null,
  request_count integer not null check (request_count > 0),
  updated_at timestamptz not null default clock_timestamp()
);

