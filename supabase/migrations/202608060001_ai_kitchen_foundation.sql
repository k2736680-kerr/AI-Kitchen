create or replace function public.ai_kitchen_list_history(
  p_locale text,
  p_limit integer,
  p_cursor_time timestamptz default null,
  p_cursor_recipe_id uuid default null
) returns table (
  recipe_id uuid,
  recipe_payload jsonb,
  source text,
  first_visited_at timestamptz,
  last_visited_at timestamptz,
  visit_count integer
)
language sql
stable
security invoker
set search_path = public, pg_temp
as $$
  select h.recipe_id, r.recipe_payload, h.source, h.first_visited_at, h.last_visited_at, h.visit_count
  from public.ai_kitchen_recipe_history h
  join public.ai_kitchen_recipes r on r.owner_id = h.owner_id and r.recipe_id = h.recipe_id
  where h.owner_id = auth.uid()
    and r.locale = p_locale
    and (
      p_cursor_time is null
      or h.last_visited_at < p_cursor_time
      or (h.last_visited_at = p_cursor_time and h.recipe_id < p_cursor_recipe_id)
    )
  order by h.last_visited_at desc, h.recipe_id desc
  limit least(greatest(p_limit, 1), 51)
$$;

create or replace function public.ai_kitchen_allow_request(p_limit integer default 10, p_window_seconds integer default 60)
returns boolean
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_owner uuid := auth.uid();
  v_row public.ai_kitchen_rate_limits%rowtype;
  v_now timestamptz := clock_timestamp();
begin
  if v_owner is null then raise exception 'authentication required'; end if;
  if p_limit < 1 or p_window_seconds < 1 then raise exception 'invalid rate limit'; end if;
  select * into v_row from public.ai_kitchen_rate_limits where owner_id = v_owner for update;
  if not found then
    insert into public.ai_kitchen_rate_limits (owner_id, window_started_at, request_count) values (v_owner, v_now, 1);
    return true;
  end if;
  if v_row.window_started_at + make_interval(secs => p_window_seconds) <= v_now then
    update public.ai_kitchen_rate_limits set window_started_at = v_now, request_count = 1, updated_at = v_now where owner_id = v_owner;
    return true;
  end if;
  if v_row.request_count >= p_limit then return false; end if;
  update public.ai_kitchen_rate_limits set request_count = request_count + 1, updated_at = v_now where owner_id = v_owner;
  return true;
end;
$$;

