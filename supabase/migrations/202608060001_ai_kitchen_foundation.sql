$$;

create or replace function public.ai_kitchen_save_recipe_success(
  p_idempotency_key text,
  p_request_hash text,
  p_response jsonb,
  p_recipes jsonb,
  p_duration_ms integer
) returns void
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
declare
  v_owner uuid := auth.uid();
  v_recipe jsonb;
  v_recipe_id uuid;
  v_metadata jsonb := p_response -> 'metadata';
begin
  if v_owner is null then raise exception 'authentication required'; end if;
  if jsonb_typeof(p_recipes) <> 'array' or jsonb_array_length(p_recipes) = 0 then raise exception 'recipes must be a non-empty array'; end if;

  for v_recipe in select value from jsonb_array_elements(p_recipes)
  loop
    v_recipe_id := (v_recipe ->> 'recipeId')::uuid;
    insert into public.ai_kitchen_recipes (
      recipe_id, owner_id, schema_version, source, provider, model, title, locale,
      cooking_method, cuisine, flavor, recipe_payload
    ) values (
      v_recipe_id,
      v_owner,
      v_metadata ->> 'recipeSchemaVersion',
      v_metadata ->> 'source',
      v_metadata ->> 'provider',
      v_metadata ->> 'model',
      v_recipe ->> 'title',
      v_recipe ->> 'locale',
      v_recipe ->> 'cookingMethod',
      v_recipe ->> 'cuisine',
      v_recipe ->> 'flavor',
      v_recipe
    )
    on conflict (recipe_id) do update set
      schema_version = excluded.schema_version,
      source = excluded.source,
      provider = excluded.provider,
      model = excluded.model,
      title = excluded.title,
      locale = excluded.locale,
      cooking_method = excluded.cooking_method,
      cuisine = excluded.cuisine,
      flavor = excluded.flavor,
      recipe_payload = excluded.recipe_payload,
      updated_at = clock_timestamp()
    where public.ai_kitchen_recipes.owner_id = v_owner;

    insert into public.ai_kitchen_recipe_history (owner_id, recipe_id, source)
    values (v_owner, v_recipe_id, 'remote')
    on conflict (owner_id, recipe_id) do update set
      source = excluded.source,
      last_visited_at = clock_timestamp(),
      visit_count = public.ai_kitchen_recipe_history.visit_count + 1;
  end loop;

  update public.ai_kitchen_generation_requests
  set status = 'succeeded', response_payload = p_response, duration_ms = p_duration_ms,
      completed_at = clock_timestamp(), updated_at = clock_timestamp(), error_code = null
  where owner_id = v_owner and idempotency_key = p_idempotency_key and request_hash = p_request_hash;
  if not found then raise exception 'generation reservation not found'; end if;
end;
$$;

create or replace function public.ai_kitchen_visit_history(p_recipe_id uuid, p_source text)
returns boolean
language plpgsql
security invoker
set search_path = public, pg_temp
as $$
begin
  if auth.uid() is null then raise exception 'authentication required'; end if;
  if p_source not in ('local', 'remote') then raise exception 'invalid history source'; end if;
  update public.ai_kitchen_recipe_history
  set source = p_source, last_visited_at = clock_timestamp(), visit_count = visit_count + 1
  where owner_id = auth.uid() and recipe_id = p_recipe_id;
  return found;
end;
$$;

